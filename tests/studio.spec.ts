import { expect, test } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

test('opens the dashboard and runs a grounded, contextual playground chat', async ({ page }, info) => {
  const screenshots = 'test-results/screenshots'
  const mobile = info.project.name === 'iphone'
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Tổng quan', exact: true })).toBeVisible()
  await expect(page.getByText('Dữ liệu mô phỏng', { exact: true })).toBeVisible()
  await expect(page.getByText('Tổng hội thoại', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBe(0)
  await mkdir(screenshots, { recursive: true })
  await page.screenshot({ path: `${screenshots}/dashboard-${info.project.name}.png`, fullPage: !mobile, animations: 'disabled' })
  await page.getByRole('link', { name: 'Mở phòng thử nghiệm' }).click()
  await page.getByRole('textbox', { name: 'Câu hỏi thử nghiệm' }).fill('Quy trình kiểm tra nội bộ')
  await page.getByRole('button', { name: 'Gửi câu hỏi' }).click()
  await expect(page.getByText('Đây là nội dung mô phỏng phục vụ kiểm thử nội bộ.', { exact: true }).first()).toBeVisible()
  await page.getByText('Quy trình kiểm tra nội bộ · Đã dùng').click()
  await expect(page.getByText('Nguồn truy xuất (1)')).toBeVisible()
  await page.screenshot({ path: `${screenshots}/playground-${info.project.name}.png`, fullPage: true, animations: 'disabled' })
  await page.getByRole('textbox', { name: 'Câu hỏi thử nghiệm' }).fill('Giá nến là bao nhiêu?')
  await page.getByRole('button', { name: 'Gửi câu hỏi' }).click()
  await expect(page.getByText('Thiếu nguồn phù hợp').first()).toBeVisible()
})

test('imports content, approves publication, and manages a catalog item', async ({ page }, info) => {
  test.skip(info.project.name !== 'desktop', 'CRUD workflows run once on desktop.')
  await page.goto('/#knowledge')
  for (const filename of ['knowledge.csv', 'knowledge.md', 'knowledge.txt']) {
    await page.getByRole('button', { name: 'Nhập tệp' }).click()
    await page.getByLabel('Tệp tri thức').setInputFiles('tests/fixtures/' + filename)
    await page.getByRole('button', { name: 'Nhập bản nháp' }).click()
    await expect(page.getByText('Đã thêm bản nháp từ tệp.')).toBeVisible()
  }
  await page.getByRole('searchbox').fill('knowledge.md')
  await expect(page.getByText('Không tìm thấy kết quả')).toBeVisible()
  await page.getByRole('searchbox').fill('hướng dẫn kiểm thử')
  await page.getByRole('button', { name: 'Duyệt', exact: true }).click()
  await page.getByRole('button', { name: 'Xuất bản', exact: true }).click()
  await expect(page.getByText('Đã xuất bản', { exact: true })).toBeVisible()
  await page.getByRole('navigation').getByText('Sản phẩm').click()
  await page.getByRole('button', { name: 'Thêm sản phẩm' }).click()
  await page.getByLabel('Tên sản phẩm').fill('Sản phẩm giả lập kiểm thử')
  await page.getByLabel('Tầng hương').fill('Chỉ dùng trong kiểm thử.')
  await page.getByLabel('Giá (VND)').fill('1000')
  await page.getByRole('button', { name: 'Lưu sản phẩm' }).click()
  await expect(page.getByText('Sản phẩm giả lập kiểm thử', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Sửa Sản phẩm giả lập kiểm thử' }).click()
  await page.getByLabel('Giá (VND)').fill('2000')
  await page.getByRole('button', { name: 'Lưu sản phẩm' }).click()
  await expect(page.getByText('2.000 ₫')).toBeVisible()
  await page.getByRole('button', { name: 'Xóa Sản phẩm giả lập kiểm thử' }).click()
  await page.getByRole('button', { name: 'Xác nhận xóa' }).click()
  await expect(page.getByText('Chưa có sản phẩm')).toBeVisible()
})

