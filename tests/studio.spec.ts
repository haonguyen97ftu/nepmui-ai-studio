test('reviews an unanswered conversation and publishes an approved correction', async ({ page }, info) => {
  const mobile = info.project.name === 'iphone'
  await page.goto('/#playground')
  const title = mobile ? 'Tài liệu đóng gói dành cho thiết bị di động' : 'Cách kiểm tra chất lượng mô phỏng máy tính'
  const correction = 'Kết quả kiểm thử phải được ghi vào nhật ký mô phỏng.'
  await page.getByRole('textbox', { name: 'Câu hỏi thử nghiệm' }).fill(title)
  await page.getByRole('button', { name: 'Gửi câu hỏi' }).click()
  await expect(page.getByText('Thiếu nguồn phù hợp').first()).toBeVisible()
  if (mobile) await page.getByRole('button', { name: 'Mở menu' }).click()
  await page.getByRole('navigation').getByText('Hội thoại', { exact: true }).click()
  await page.getByLabel('Cần hỗ trợ', { exact: true }).check()
  await page.getByRole('link', { name: new RegExp(title) }).click()
  await expect(page.locator('.transcript')).toBeVisible()
  await page.screenshot({ path: `test-results/screenshots/conversations-${info.project.name}.png`, fullPage: true, animations: 'disabled' })
  await page.getByLabel('Trạng thái xử lý').selectOption('resolved')
  await page.getByLabel('Phản hồi nội bộ').fill('Đã kiểm tra yêu cầu mô phỏng.')
  await page.getByRole('button', { name: 'Lưu xử lý' }).click()
  await expect(page.getByText('Đã lưu xử lý nội bộ.')).toBeVisible()
  await page.getByRole('button', { name: 'Tạo bản sửa phản hồi' }).click()
  await expect(page.getByLabel('Câu hỏi', { exact: true })).toHaveValue(title)
  await page.getByLabel('Phản hồi đã sửa').fill(correction)
  await page.screenshot({ path: `test-results/screenshots/training-${info.project.name}.png`, fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Lưu bản nháp' }).click()
  const row = page.getByRole('listitem').filter({ hasText: title })
  await row.getByRole('button', { name: 'Duyệt', exact: true }).click()
  await row.getByRole('button', { name: 'Xuất bản', exact: true }).click()
  await expect(page.getByText('Đã xuất bản vào kho tri thức.')).toBeVisible()
  if (mobile) await page.getByRole('button', { name: 'Mở menu' }).click()
  await page.getByRole('navigation').getByText('Phòng thử nghiệm').click()
  await page.getByRole('textbox', { name: 'Câu hỏi thử nghiệm' }).fill(title)
  await page.getByRole('button', { name: 'Gửi câu hỏi' }).click()
  await expect(page.locator('.transcript').getByText(correction, { exact: true })).toBeVisible()
})

